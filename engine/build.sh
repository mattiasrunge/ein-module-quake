#!/bin/sh
# Compiles Quake to WebAssembly in quakegeneric's patched source tree, the current directory, into
# /out: the game the page plays (quake.js, quake.wasm) and its dedicated server, which the
# quake-server service runs in a worker (quake-server.js, quake-server.wasm). Run by
# engine/Containerfile in the emsdk image; `client` or `server` builds one of them.
set -eu

# The engine's sources: quakegeneric's makefile's list without its null system, sound and CD
# drivers, its network of the loopback alone and its own start-up; this build's network in its place
# (net_ein.c, with id's datagram driver, net_dgrm.c).
COMMON="chase cl_demo cl_input cl_main cl_parse cl_tent cmd common console crc cvar d_edge d_fill d_init d_modech d_part d_polyse d_scan d_sky d_sprite d_surf d_vars d_zpoint draw host_cmd host in_null keys mathlib menu model net_loop net_main net_dgrm net_ein net_vcr nonintel pr_cmds pr_edict pr_exec r_aclip r_alias r_bsp r_draw r_edge r_efrag r_light r_main r_misc r_part r_sky r_sprite r_surf r_vars sbar screen sv_main sv_move sv_phys sv_user vid_null view wad world zone sys_ein"
# The game's: the page's frame, keys and mouse, id's mixer with the page's sound card, and the page's CD.
CLIENT="snd_dma snd_mem snd_mix quakegeneric_ein snd_ein cd_ein"
# The dedicated server's: no frame and no sound (quakegeneric's null sound and CD).
SERVER="snd_null cd_null server_ein"

# The frame: 640 by 480, WinQuake's VGA mode, drawn by the software renderer.
WIDTH=640
HEIGHT=480

sources() {
  for name in "$@"; do echo "$name.c"; done
}

# Quake's Host_Error leaves a frame with longjmp, which Emscripten's own setjmp handles. The glue is
# headed with Deno's ignore comments, so core's `deno fmt` and `deno lint` pass over the generated
# file.
link() {
  name=$1
  shift
  emcc -O2 -std=gnu99 -w -DQUAKEGENERIC_RES_X=$WIDTH -DQUAKEGENERIC_RES_Y=$HEIGHT "$@" -o "/out/$name.js" \
    -sMODULARIZE=1 -sEXPORT_ES6=1 -sENVIRONMENT=web \
    -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=128MB -sSTACK_SIZE=1MB \
    -sSUPPORT_LONGJMP=emscripten \
    -sEXPORTED_RUNTIME_METHODS=FS,HEAPU8,HEAP16,HEAPU32,stringToNewUTF8,UTF8ToString \
    -sFORCE_FILESYSTEM=1
  { printf '%s\n' '// deno-fmt-ignore-file' '// deno-lint-ignore-file' '// Generated by engine/Containerfile with Emscripten. Do not edit.'; cat "/out/$name.js"; } > "/out/$name.js.new"
  mv "/out/$name.js.new" "/out/$name.js"
}

mkdir -p /out
case "${1:-all}" in all | client)
  link quake $(sources $COMMON $CLIENT) -sEXPORT_NAME=createQuake \
    -sEXPORTED_FUNCTIONS=_ein_start,_ein_tick,_ein_key,_ein_mouse,_ein_disconnect,_ein_write_config,_ein_screen,_ein_width,_ein_height,_ein_frames,_ein_audio_rate,_ein_audio_render,_malloc
  ;;
esac
# The server runs in a Deno worker, which Emscripten's web runtime suits once it is handed the wasm.
case "${1:-all}" in all | server)
  link quake-server $(sources $COMMON $SERVER) -sEXPORT_NAME=createQuakeServer \
    -sEXPORTED_FUNCTIONS=_ein_start,_ein_tick,_ein_status,_malloc
  ;;
esac
